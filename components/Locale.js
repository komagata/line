// An empty or invalid preference follows Qt's system locale; only Japanese maps to ja.
function resolveLanguage(saved, systemLocale) {
    if (saved === 'ja' || saved === 'en') return saved
    return /^ja(?:[_-]|$)/i.test(systemLocale || '') ? 'ja' : 'en'
}
